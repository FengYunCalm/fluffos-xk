#!/usr/bin/env python3
"""Test incremental generation in a private source copy, never in the working tree."""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
import shutil
import sys
import time

spec = importlib.util.spec_from_file_location(
    "generated_dependency_runner",
    Path(__file__).resolve().parents[1] / "testsuite/run-targeted.py",
)
runner = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = runner
spec.loader.exec_module(runner)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence-dir", required=True)
    parser.add_argument("--cmake-arg", action="append", default=[])
    options = parser.parse_args()
    if any(not value.startswith("-D") for value in options.cmake_arg):
        parser.error("--cmake-arg accepts only -D cache definitions")
    session = runner.EvidenceSession(options.evidence_dir)
    root = Path(__file__).resolve().parents[2]
    source = session.root / "source"
    build = session.root / "build"
    before = runner.repository_manifest(root)
    for name in before:
        destination = source / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(root / name, destination)
    if before != runner.repository_manifest(root):
        raise runner.RunnerError("source changed during snapshot")
    if any(runner.file_identity(source / name) != identity for name, identity in before.items()):
        raise runner.RunnerError("source snapshot differs")
    (session.root / "source-snapshot.json").write_text(json.dumps(before, indent=2) + "\n")

    def run(command: list[str], label: str) -> None:
        result = runner.run_process(
            session, command, cwd=source, environment=runner.command_environment(source),
            timeout=240, label=label,
        )
        if result.returncode or result.timed_out or result.failure_reason:
            raise runner.RunnerError(f"{label} failed: {result.log_path}")
        runner.reject_sanitizer_output(result.output)

    run(["cmake", "-S", str(source), "-B", str(build), "-DCMAKE_BUILD_TYPE=Debug",
         "-DENABLE_LTO=OFF", "-DMARCH_NATIVE=OFF", "-DCMAKE_DISABLE_FIND_PACKAGE_BISON=TRUE",
         *options.cmake_arg], "configure")
    build_command = ["cmake", "--build", str(build), "--target", "autogen", "--parallel", "4"]
    run(build_command, "initial-build")
    cases = (
        ("local_options", source / "src/local_options", "LOCAL", "options.autogen.h"),
        ("options_internal", source / "src/base/internal/options_internal.h", "INTERNAL",
         "options.autogen.h"),
        ("config", build / "src/config.h", "CONFIG", "options.autogen.h"),
        ("packages", build / "src/packages/packages.autogen.h", "PACKAGE", "options.autogen.h"),
        ("spec", source / "src/packages/core/core.spec", "SPEC", "efuns.autogen.h"),
        ("applies", source / "src/vm/internal/applies", "APPLIES", "applies_table.autogen.h"),
        ("tool", source / "src/tools/make_options_defs.cc", "TOOL", "options.autogen.h"),
    )
    results = []
    for name, path, suffix, output in cases:
        original = path.read_bytes()
        marker = f"U06_DEPENDENCY_{suffix}"
        changed = original + f"\n#define {marker} 17\n".encode()
        if name == "spec":
            marker = "u06_generated_probe"
            changed = original + f"\nvoid {marker}();\n".encode()
        elif name == "applies":
            changed = original + f"\n{marker}\n".encode()
        elif name == "tool":
            changed = original.replace(b"Automatically generated by make_options_def.py.",
                                       f"Automatically generated {marker}.".encode())
        if changed == original:
            raise runner.RunnerError(f"fixture did not change {path}")
        output_path = build / "src" / output
        spec_path = source / "src/packages/core/core.spec"
        spec_original = spec_path.read_bytes()
        check_fullspec = name in ("local_options", "options_internal", "config", "packages")
        function_name = marker.lower()
        if check_fullspec:
            time.sleep(3)
            spec_path.write_bytes(spec_original + (
                f"\n#ifdef {marker}\nvoid {function_name}();\n#endif\n"
            ).encode())
            run(build_command, f"{name}-conditional-spec")
        try:
            # WSL clock adjustments can briefly leave build outputs in the future.
            time.sleep(3)
            path.write_bytes(changed)
            outputs = [output_path]
            if check_fullspec:
                outputs.append(build / "src/efuns.autogen.h")
            if path.stat().st_mtime_ns <= max(item.stat().st_mtime_ns for item in outputs):
                raise runner.RunnerError(f"input is not newer than output: {path}")
            run(build_command, name)
            passed = marker in output_path.read_text()
            if check_fullspec:
                passed = passed and function_name in (build / "src/efuns.autogen.h").read_text()
            results.append({"case": name, "passed": passed})
            print(f"{name}: {'PASS' if passed else 'FAIL'}", flush=True)
        finally:
            time.sleep(3)
            path.write_bytes(original)
            if check_fullspec:
                spec_path.write_bytes(spec_original)
            run(build_command, f"{name}-restore")
    passed = len(results) == len(cases) and all(item["passed"] for item in results)
    (session.root / "test-summary.json").write_text(json.dumps({
        "passed": passed, "expected": len(cases), "results": results,
    }, indent=2) + "\n")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
